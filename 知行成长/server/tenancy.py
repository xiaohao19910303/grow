"""Trusted request identity, isolated module instances and filesystem roots.

ContextVars propagate into FastAPI worker threads and asyncio background tasks.
User IDs and schema names are generated by the server, never accepted from headers.
"""
from contextvars import ContextVar
import json
from pathlib import Path
from threading import RLock

from copilot.core import Problem

current_user = ContextVar('current_learning_user', default=None)
_proxies = []


def learning_root(default):
    user = current_user.get()
    return Path(default) if not user or user['is_owner'] else Path(default).parent / '.users' / user['id'] / 'materials'


def runtime_root(default):
    user = current_user.get()
    return Path(default) if not user or user['is_owner'] else Path(default) / 'users' / user['id']


class Scoped:
    def __init__(self, factory, initialize=False):
        object.__setattr__(self, '_factory', factory)
        object.__setattr__(self, '_initialize', initialize)
        object.__setattr__(self, '_instances', {})
        object.__setattr__(self, '_lock', RLock())
        _proxies.append(self)

    def resolve(self):
        user = current_user.get()
        # The original owner's default services already run at startup (including
        # daily collection). Reuse them so login never restarts in-flight jobs.
        key = user['id'] if user and (not user['is_owner'] or json.loads(user.get('github_config') or '{}').get('mode') == 'custom') else None
        with self._lock:
            if key not in self._instances:
                instance = self._factory()
                if user and self._initialize:
                    import db
                    try:
                        instance.initialize()
                        instance.startup_error = None
                    except (Problem, OSError, db.psycopg2.Error) as exc:
                        instance.startup_error = exc if isinstance(exc, Problem) else Problem(
                            'storage_unavailable', '此模块存储暂不可用，请检查服务端配置。', 503)
                self._instances[key] = instance
            return self._instances[key]

    def __getattr__(self, name):
        return getattr(self.resolve(), name)

    def __setattr__(self, name, value):
        setattr(self.resolve(), name, value)


def scoped(app, factory, initialize=False):
    return Scoped(factory, initialize) if getattr(app.state, 'multiuser', False) else factory()


def reset_user(user_id):
    for proxy in _proxies:
        with proxy._lock:
            proxy._instances.pop(user_id, None)


async def shutdown_all():
    # Tasks retain the originating identity while cancelling and journaling.
    for proxy in _proxies:
        for instance in list(proxy._instances.values()):
            shutdown = getattr(instance, 'shutdown', None)
            if shutdown:
                await shutdown()
